"""scripts/compat_matrix.py (roadmap 46): the cell format, the rendered table, and that docs/compatibility.md is
current.

The doc is a pure function of the data block embedded in it, so a hand edit, a stale render or a changed format all
fail here; the format itself is pinned by rendering two fixed cells and comparing every line.
"""

import copy
import importlib.util
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("compat_matrix", ROOT / "scripts" / "compat_matrix.py")
assert spec is not None and spec.loader is not None
cm = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cm)


def _cell(ferric="0.1.0rc12", status="pass", smeltery="0.1.1.dev5+gabc", date="2026-11-20", floor_ok=True, **tests):
    return {
        "schema": cm.CELL_SCHEMA,
        "date": date,
        "python": "3.11.15",
        "platform": "linux-x86_64",
        "smeltery": {
            "requirement": "the source checkout",
            "source_sha": "a" * 40,
            "source_dirty": False,
            "version": smeltery,
        },
        "ferric": {
            "label": ferric,
            "kind": "pypi",
            "requested": f"ferric=={ferric}",
            "floor": ">=0.1.0rc10",
            "satisfies_floor": floor_ok,
            "version": ferric,
            "build_sha": "b" * 40,
            "build_dirty": False,
            "from_index": True,
        },
        "checks": {
            "install": {"status": "pass", "detail": "ok"},
            "tests": {
                "status": "pass" if status == "pass" else "fail",
                "passed": 66,
                "failed": 0 if status == "pass" else 1,
                "skipped": 4,
                "files": [],
                "missing": [],
                "detail": "" if status == "pass" else "tests/test_anchors.py::test_x",
                **tests,
            },
            "example": {"status": "pass", "detail": "ferric.__build__: VERIFIED"},
        },
        "status": status,
    }


def test_parse_ferric_spec_forms():
    assert cm.parse_ferric("0.1.0rc12") == {"label": "0.1.0rc12", "kind": "pypi", "requirement": "ferric==0.1.0rc12"}
    assert cm.parse_ferric("==0.1.0rc11")["requirement"] == "ferric==0.1.0rc11"
    main = cm.parse_ferric("main")
    assert main == {
        "label": "main",
        "kind": "git",
        "requirement": "ferric @ git+https://github.com/mgoldey/ferric@main",
    }
    assert cm.parse_ferric("git+https://github.com/mgoldey/ferric@abc123")["label"] == "git:abc123"
    wheel = cm.parse_ferric("main=/w/ferric-0.1.0.dev0-cp311-cp311-linux_x86_64.whl")
    assert wheel["label"] == "main" and wheel["kind"] == "wheel" and wheel["requirement"].startswith("ferric @ file://")
    assert wheel["display"] == "ferric @ ferric-0.1.0.dev0-cp311-cp311-linux_x86_64.whl"
    assert cm.parse_ferric("/w/ferric-0.1.0.dev0-cp311-abi3-x.whl")["label"] == "wheel:0.1.0.dev0"
    with pytest.raises(ValueError):
        cm.parse_ferric("latest please")


def test_with_extra_puts_the_extra_before_the_specifier():
    assert cm.with_extra("smeltery==0.1.0", "posebusters") == "smeltery[posebusters]==0.1.0"
    assert (
        cm.with_extra("smeltery[mcp] @ git+https://x/y", "posebusters") == "smeltery[mcp,posebusters] @ git+https://x/y"
    )
    assert cm.with_extra("smeltery[posebusters]", "posebusters") == "smeltery[posebusters]"


def test_the_floor_is_read_from_pyproject_and_filters_the_index():
    floor = cm.declared_ferric(ROOT / "pyproject.toml")
    assert floor.startswith(">=")
    payload = {
        "releases": {
            "0.1.0rc8": [{"yanked": False}],
            "0.1.0rc10": [{"yanked": False}],
            "0.1.0rc9": [],
            "0.1.0rc11": [{"yanked": True}],
            "0.1.0rc12": [{"yanked": False}],
            "0.1.0rc2": [{"yanked": False}],
        }
    }
    assert cm.releases_satisfying(payload, ">=0.1.0rc10") == ["0.1.0rc10", "0.1.0rc12"]
    assert cm.satisfies("0.1.0rc12", ">=0.1.0rc10") and not cm.satisfies("0.1.0rc8", ">=0.1.0rc10")


def test_lock_constraints_drop_ferric_and_keep_every_other_pin():
    export = (
        "# This file was autogenerated by uv\n-e .\nferric==0.1.0rc10\n    # via smeltery\n"
        "numpy==2.4.6 ; python_full_version < '3.12'\nrdkit==2026.3.6\nferric @ git+https://x\n"
    )
    assert cm.lock_constraints(export) == "numpy==2.4.6 ; python_full_version < '3.12'\nrdkit==2026.3.6\n"


def test_junit_counts_count_errors_as_failures():
    xml = '<testsuites><testsuite tests="10" failures="1" errors="1" skipped="2"/></testsuites>'
    assert cm.junit_counts(xml) == {"passed": 6, "failed": 2, "skipped": 2}


def test_record_identity_needs_verified_provenance_and_the_installed_build():
    rec = {"ferric": {"commit": "b" * 40, "version": "0.1.0rc12", "provenance": "VERIFIED from ferric.__build__"}}
    assert cm.record_identity_problem(rec, {"git_sha": "b" * 40}, "0.1.0rc12") is None
    assert "commit" in cm.record_identity_problem(rec, {"git_sha": "c" * 40}, "0.1.0rc12")
    assert cm.record_identity_problem(rec, None, "0.1.0rc12") is None
    assert "0.1.0rc11" in cm.record_identity_problem(rec, None, "0.1.0rc11")
    unverified = {"ferric": {**rec["ferric"], "provenance": "UNVERIFIED"}}
    assert "not VERIFIED" in cm.record_identity_problem(unverified, {"git_sha": "b" * 40}, "0.1.0rc12")


def test_merge_keeps_the_newest_cell_per_smeltery_ferric_and_python():
    old = _cell(date="2026-11-01", status="fail")
    new = _cell(date="2026-11-20")
    other = _cell(ferric="0.1.0rc11")
    merged = cm.merge([old, other], [new])
    assert [(c["ferric"]["label"], c["status"]) for c in merged] == [("0.1.0rc11", "pass"), ("0.1.0rc12", "pass")]
    assert cm.merge([new], [old]) == [new]  # an older cell never replaces a newer one


def test_the_rendered_format_is_pinned():
    cells = [_cell(), _cell(ferric="0.1.0rc8", status="fail", floor_ok=False)]
    text = cm.render(cells)
    lines = text.splitlines()
    assert lines[0] == "# Compatibility: smeltery x ferric"
    i = lines.index("## Matrix")
    assert lines[i + 2 : i + 5] == [
        "| smeltery | Python | ferric 0.1.0rc8 | ferric 0.1.0rc12 |",
        "|---|---|---|---|",
        "| `0.1.1.dev5+gabc` | 3.11 | **FAIL** (below floor) | pass |",
    ]
    j = lines.index("## Cells")
    assert lines[j + 2 : j + 6] == [
        "| smeltery | from tree | ferric | installed | build | tests (pass/fail/skip) | example | date | platform |",
        "|---|---|---|---|---|---|---|---|---|",
        "| `0.1.1.dev5+gabc` | aaaaaaaa | 0.1.0rc8 | 0.1.0rc8 | bbbbbbbb | 66/1/4 | pass | 2026-11-20 "
        "| linux-x86_64, py3.11.15 |",
        "| `0.1.1.dev5+gabc` | aaaaaaaa | 0.1.0rc12 | 0.1.0rc12 | bbbbbbbb | 66/0/4 | pass | 2026-11-20 "
        "| linux-x86_64, py3.11.15 |",
    ]
    assert "- `0.1.1.dev5+gabc` x ferric 0.1.0rc8, `tests`: tests/test_anchors.py::test_x" in lines
    # the data round-trips, and rendering is deterministic
    assert cm.doc_cells(text) == cm.merge([], cells)
    assert cm.render(copy.deepcopy(cells)[::-1]) == text


def test_main_columns_sort_after_releases_and_not_installable_is_said():
    cell = _cell(ferric="main", status="not-installable", floor_ok=None)
    cell["checks"] = {"install": {"status": "fail", "detail": "no libint2"}}
    text = cm.render([_cell(), cell])
    assert "| smeltery | Python | ferric 0.1.0rc12 | ferric main |" in text
    assert "| `0.1.1.dev5+gabc` | 3.11 | pass | not installable |" in text


def test_the_committed_doc_is_exactly_the_render_of_its_own_data():
    doc = (ROOT / "docs" / "compatibility.md").read_text()
    cells = cm.doc_cells(doc)
    assert cells, "docs/compatibility.md carries no compat-data block"
    assert all(c["schema"] == cm.CELL_SCHEMA and c["status"] in cm.STATUSES for c in cells)
    assert doc == cm.render(cells), "docs/compatibility.md was edited by hand or rendered by an older generator"


def test_the_committed_table_names_where_it_came_from():
    cells = cm.doc_cells((ROOT / "docs" / "compatibility.md").read_text())
    for c in cells:
        assert c["date"] and c["platform"] and c["python"] and c["smeltery"]["version"], json.dumps(c)
        assert c["smeltery"]["source_sha"] is None or len(c["smeltery"]["source_sha"]) == 40


def test_the_workflow_runs_the_script_and_never_pushes():
    wf = (ROOT / ".github" / "workflows" / "compat.yml").read_text()
    assert "scripts/compat_matrix.py list-ferric" in wf and "scripts/compat_matrix.py run" in wf
    assert "scripts/compat_matrix.py render" in wf and "--fail-on-supported-failure" in wf
    assert "git push" not in wf and "contents: write" not in wf
    assert 'tags: ["v*"]' in wf and "schedule:" in wf
