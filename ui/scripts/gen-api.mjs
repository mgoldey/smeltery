// Generate src/api/schema.d.ts from the Bench API's OpenAPI schema (python -m smeltery.bench.openapi).
// BENCH_PYTHON overrides the interpreter; the default is the repo's .venv.
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..", "..");
const venv = resolve(repo, ".venv", "bin", "python");
const python = process.env.BENCH_PYTHON ?? (existsSync(venv) ? venv : "python3");
const json = execFileSync(python, ["-m", "smeltery.bench.openapi"], { cwd: repo, encoding: "utf8", maxBuffer: 1 << 26 });
const ast = await openapiTS(JSON.parse(json));
const banner = "// Generated by `npm run gen:api` from the Bench API's OpenAPI schema. Do not edit.\n";
writeFileSync(resolve(here, "..", "src", "api", "schema.d.ts"), banner + astToString(ast));
console.log("wrote src/api/schema.d.ts");
